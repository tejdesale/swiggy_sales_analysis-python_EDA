"""## **KPI's**

**Total Sales**
"""

total_sales = df["Price (INR)"].sum()
print("Total Sales (INR):",total_sales)

"""**Average Rating**"""

avg_rating = df["Rating"].mean()
print("Average rating:",round(avg_rating,2))

"""**Average Order Value**"""

avg_order_value = df["Price (INR)"].mean()
print("Average order value (INR) is :",round(avg_order_value,2))

